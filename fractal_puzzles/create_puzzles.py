"""Create Fractal Jigsaw Puzzle POD products on Printify (blueprint 616 /
provider 1 SPOKE; 120 / 252 / 500 pieces, 5:4 landscape) and push each to the
connected Etsy shop. Reuses existing fractal masters, cropped to 5:4.

  python create_puzzles.py
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
MAST = os.path.join(HERE, "masters")
sys.path.insert(0, os.path.join(REPO, "printify")); sys.path.insert(0, REPO)
import printify_publish as pp

BP, PROVIDER = 616, 1
SIZES = {72663: 2300, 72664: 2900, 72665: 3900}   # 120 / 252 / 500 pcs

TAGS = ["fractal puzzle", "jigsaw puzzle", "math puzzle", "fractal art",
        "chaos theory art", "science gift", "math gift", "adult puzzle",
        "geometric puzzle", "unique puzzle", "mathematician gift", "brain teaser",
        "julia set art"]

# (crop file, Name, blurb)
PUZZLES = [
    ("julia_dense.jpg", "Julia Filament", "a Julia-set fractal (z -> z² + c) with endless self-similar spirals"),
    ("julia_pinwheel.jpg", "Julia Pinwheel", "a Julia-set fractal whose arms spiral into infinite detail"),
    ("chaos_6.jpg", "Magnetic Pendulum · Six Magnets", "the basins of attraction of a pendulum over six magnets"),
    ("chaos_5.jpg", "Magnetic Pendulum · Five Magnets", "the basins of attraction of a pendulum over five magnets"),
]

DESC = """Fractal Jigsaw Puzzle — {name}. Made to order.

{blurb}. Every pixel is computed from the mathematics — no clip-art, no AI — so
the detail keeps going right down to the last piece: a genuinely challenging,
beautiful puzzle.

- Sturdy chipboard jigsaw puzzle, vivid printing
- Sizes: 120, 252 and 500 pieces (choose above)
- Made and shipped to order by our print partner

A great gift for mathematicians, scientists, teachers and puzzle lovers.
Designed and generated by MathRelaxing."""


def upscaled(fn, target_w=6200):
    im = Image.open(os.path.join(MAST, fn)).convert("RGB")
    if im.width < target_w:
        r = target_w / im.width
        im = im.resize((target_w, int(im.height * r)), Image.LANCZOS)
    out = os.path.join(HERE, "_pf_" + fn)
    im.save(out, quality=95)
    return out


def main():
    results = []
    for fn, name, blurb in PUZZLES:
        title = (f"Fractal Jigsaw Puzzle | {name} | Math Chaos Art Puzzle 252 or 500 Piece")[:140]
        print("\n===", fn, "===")
        up = pp.upload_image(upscaled(fn), file_name=f"puzzle_{fn}")
        img_id = up if isinstance(up, str) else up["id"]
        prod = pp.create_poster(title, DESC.format(name=name, blurb=blurb), img_id, SIZES,
                                tags=TAGS, blueprint_id=BP, provider_id=PROVIDER)
        pid = prod["id"]; pp.publish_product(pid)
        print(f"  published {pid} -> Etsy")
        results.append((name, pid))
    print("\n=== SUMMARY ===")
    for name, pid in results:
        print(f"  {name}: printify {pid}")


if __name__ == "__main__":
    main()
