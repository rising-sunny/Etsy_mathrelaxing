"""Create the DRAFT Etsy listing for the hardcover art book
'The Mathematics of Beauty' with TWO hardcover variants (Standard $48 /
Premium $65). Stays in DRAFT — the owner activates it manually.

Record: first created 2026-07-26 as draft listing_id=4544209146
(state=draft, physical, taxonomy 335 Art & Photography Books, 8 images,
two variants via the inventory endpoint — see update_book_inventory.py).

Preview images are expected under ../fullbook/previews/ (built by
build_previews.py). Etsy auth uses etsy_token.json at the repo root.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
PREV = os.path.join(HERE, "..", "fullbook", "previews")
sys.path.insert(0, REPO)
os.chdir(REPO)  # etsy_token.json is cwd-relative
import etsy_manager

# physical Lulu-book profiles (from products_catalog.py)
SHIPPING_PROFILE = 310608167423
READINESS_STATE = 1498071010932
RETURN_POLICY = 1496849341269
TAXONOMY_ART_BOOK = 335          # Books > Art & Photography Books
CUSTOM_PROP = 513                # Etsy "Custom Property 1"

TITLE = ("The Mathematics of Beauty | Hardcover Math Art Book | 38 Plates of "
         "Fractals, Attractors and Curves | Square Coffee Table Gallery Book")

BASE_PRICE = 48.00  # standard; premium set via inventory

TAGS = [
    "math art book", "coffee table book", "hardcover art book", "gift for math lover",
    "generative art", "fractal art", "mathematician gift", "math teacher gift",
    "geometric art book", "strange attractor", "science art book", "chaos theory art",
    "math gallery book",
]

DESC = """THE MATHEMATICS OF BEAUTY
A premium hardcover gallery of mathematical art.

Some equations do more than compute — they draw. This square, coffee-table hardcover pairs 38 beautiful mathematical forms with the elegant equation behind each one and a short note. Strange attractors and fractals, curves and waves, the symmetry of tilings — every plate is generated directly from its own formula. Nothing traced, nothing drawn by hand.

— TWO EDITIONS (choose above) —
- Standard Hardcover ($48): case-wrap hardcover, premium coated paper, matte cover.
- Premium Hardcover ($65): the same gallery printed on heavier, gallery-weight coated stock for deeper blacks and richer color.

— WHAT'S INSIDE —
- 38 full-page plates across five chapters: Strange Attractors, Fractals, Curves, Waves & Fields, and Tilings
- Every plate: the artwork, its elegant equation, and a short description
- 88 pages, square 8.5 x 8.5 in (21.6 x 21.6 cm)
- Case-wrap hardcover, matte cover, premium coated interior

— A NOTE ON MAKING —
Each book is printed to order by our print partner, so it arrives fresh and perfectly bound. Please allow a few days for production before it ships.

— PERFECT FOR —
A gift for a mathematician, physicist, engineer, teacher or student — or a striking piece for any coffee table, studio or office shelf.

Designed and generated by MathRelaxing."""

IMAGES = [
    "01_hero_lifestyle.jpg", "02_dark_marble.jpg", "03_white_marble.jpg",
    "04_back_cover.jpg", "05_inside_lorenz.jpg", "06_inside_lissajous.jpg",
    "07_inside_bessel.jpg", "08_inside_grid.jpg",
]

# (sku, Edition label <=45 chars, price)
VARIANTS = [
    ("TMB-STD-8585",  "Standard Hardcover", 48.00),
    ("TMB-PREM-8585", "Premium Hardcover",  65.00),
]


def main():
    assert len(TITLE) <= 140, f"title too long: {len(TITLE)}"
    assert TITLE.count("&") <= 1
    assert not any(ch in TITLE for ch in "^=+"), "forbidden char in title"
    for _, v, _ in VARIANTS:
        assert len(v) <= 45
    print(f"title {len(TITLE)} chars OK | tags {len(TAGS)} | base ${BASE_PRICE}")

    m = etsy_manager.EtsyManager()
    lid = m.create_draft_listing(
        TITLE, DESC, BASE_PRICE, TAXONOMY_ART_BOOK, is_digital=False, quantity=100,
        tags=TAGS, shipping_profile_id=SHIPPING_PROFILE,
        readiness_state_id=READINESS_STATE, return_policy_id=RETURN_POLICY)
    print("draft listing id:", lid)

    try:
        m.update_listing(lid, who_made="i_did", when_made="made_to_order", is_supply=False)
    except Exception as e:
        print("  attrs PATCH warn:", str(e)[:160])

    for rank, fn in enumerate(IMAGES, start=1):
        p = os.path.join(PREV, fn)
        try:
            m.upload_listing_image(lid, p, rank=rank)
        except Exception as e:
            print(f"  image {fn} err:", str(e)[:160])

    set_variants(m, lid)

    print("\nDONE. Draft listing", lid, "(state=draft).")
    print(f"URL: https://www.etsy.com/listing/{lid}")


def set_variants(m, lid):
    """Two hardcover variants via the inventory endpoint. Physical made-to-order
    offerings require a per-OFFERING readiness_state_id (per-product is rejected
    with 'Array contains invalid keys: readiness_state_id')."""
    prods = []
    for sku, label, price in VARIANTS:
        prods.append({
            "sku": sku,
            "property_values": [{
                "property_id": CUSTOM_PROP, "property_name": "Edition",
                "scale_id": None, "value_ids": [], "values": [label],
            }],
            "offerings": [{"price": price, "quantity": 100, "is_enabled": True,
                           "readiness_state_id": READINESS_STATE}],
        })
    inv = {"products": prods, "price_on_property": [CUSTOM_PROP],
           "quantity_on_property": [], "sku_on_property": [CUSTOM_PROP]}
    try:
        m.make_request("PUT", f"/listings/{lid}/inventory", payload=inv, json_body=True)
        print("  variants set: Standard $48 / Premium $65")
    except Exception as e:
        print("  inventory PUT err:", str(e)[:300])


if __name__ == "__main__":
    main()
