"""Create the DRAFT Etsy listing for the printable bookmark set. Digital
(instant download): uploads the ZIP as the file + listing images. DRAFT only.

Record: first created 2026-07-26 as draft listing_id=4544427938
(state=draft, type=download, price $5.50, 5 images + MathRelaxing_Bookmarks.zip).

Expects the package built by build_package.py:
    ./MathRelaxing_Bookmarks.zip   (the buyer download)
    ./listing/01_hero.jpg 02_detail_dark.jpg 03_detail_cream.jpg 05_sheet.jpg 04_included.jpg
Etsy auth uses etsy_token.json at the repo root.
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
LST = os.path.join(HERE, "listing")
ZIP = os.path.join(HERE, "MathRelaxing_Bookmarks.zip")
sys.path.insert(0, REPO)
os.chdir(REPO)  # etsy_token.json is cwd-relative
import etsy_manager

TITLE = ("Printable Math Bookmarks Set of 10 | The Mathematics of Beauty | Equation "
         "and Curve Art Bookmarks | Book Lover Gift | Instant Download")
PRICE = 5.50
TAXONOMY = 2078   # Digital Prints

TAGS = [
    "printable bookmark", "math bookmark", "bookmark set", "book lover gift",
    "math gift", "reader gift", "digital bookmark", "equation art",
    "math teacher gift", "science gift", "STEM gift", "bookmark printable",
    "book club gift",
]

DESC = """THE MATHEMATICS OF BEAUTY — Printable Bookmarks
A set of 10 elegant bookmarks where the art IS the mathematics — each design is generated directly from its equation.

Instant download, print at home. A perfect little gift for readers, students, teachers and anyone who loves math and beautiful things.

— WHAT YOU GET —
- 10 unique bookmark designs (Golden Spiral, Rose Curve, Euler's Identity, Lissajous, Harmonograph, Butterfly Curve, Lemniscate, Heart Curve, Phyllotaxis, Standing Wave)
- High-resolution 300 DPI PNG files (one per design)
- Print-ready sheets: US Letter AND A4, with cut marks
- A quick print & finish guide (PDF)
- Each bookmark is 2 x 6 in (5 x 15 cm)

— HOW IT WORKS —
1. Buy and download instantly (a ZIP file).
2. Print the US Letter or A4 sheet at 100% / Actual size on cardstock.
3. Cut along the corner marks. Optional: laminate, and add a tassel.

— PLEASE NOTE —
- Digital download only — nothing will be shipped.
- For personal use. Colors may vary slightly by screen and printer.

Designed and generated by MathRelaxing. Pairs beautifully with our hardcover art book, The Mathematics of Beauty."""

IMAGES = ["01_hero.jpg", "02_detail_dark.jpg", "03_detail_cream.jpg", "05_sheet.jpg", "04_included.jpg"]


def main():
    assert len(TITLE) <= 140, f"title too long: {len(TITLE)}"
    assert TITLE.count("&") <= 1
    assert not any(ch in TITLE for ch in "^=+"), "forbidden char"
    assert os.path.exists(ZIP), "zip missing — run build_package.py first"
    print(f"title {len(TITLE)} chars OK | tags {len(TAGS)} | price ${PRICE}")

    m = etsy_manager.EtsyManager()
    lid = m.create_draft_listing(TITLE, DESC, PRICE, TAXONOMY, is_digital=True,
                                 quantity=999, tags=TAGS)
    print("draft listing id:", lid)

    for rank, fn in enumerate(IMAGES, start=1):
        try:
            m.upload_listing_image(lid, os.path.join(LST, fn), rank=rank)
        except Exception as e:
            print(f"  image {fn} err:", str(e)[:160])
    try:
        m.upload_listing_file(lid, ZIP)
    except Exception as e:
        print("  file err:", str(e)[:160])

    print("\nDONE. Draft listing", lid, "(state=draft).")
    print(f"URL: https://www.etsy.com/listing/{lid}")


if __name__ == "__main__":
    main()
