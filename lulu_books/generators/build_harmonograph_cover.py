# 2. New background pattern: Harmonograph curves
def make_harmonograph_pattern(out_png, w_in, h_in, dpi=200, color="white", alpha=0.08,
                 spacing_in=1.8, motif_r=0.7, lw=0.9):
    fig = plt.figure(figsize=(w_in, h_in), dpi=dpi)
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, w_in)
    ax.set_ylim(0, h_in)
    ax.set_aspect("equal")
    ax.axis("off")
    
    # We get paths
    motif_a_lines = generate_harmonograph(123)
    motif_b_lines = generate_harmonograph(456)
    
    # Scale motifs
    def scale_motif(lines, scale):
        return [line * scale for line in lines]
        
    motif_a = scale_motif(motif_a_lines, motif_r * 0.5)
    motif_b = scale_motif(motif_b_lines, motif_r * 0.5)
    
    nx = int(w_in / spacing_in) + 3
    ny = int(h_in / (spacing_in * 0.92)) + 3
    idx = 0
    for iy in range(ny):
        for ix in range(nx):
            cx = ix * spacing_in + (spacing_in / 2 if iy % 2 else 0) - spacing_in / 2
            cy = iy * spacing_in * 0.92 - spacing_in / 2
            
            m_lines = motif_a if (ix + iy) % 2 == 0 else motif_b
            
            # Subtle rotation
            rot = np.deg2rad((idx * 15) % 360)
            c_angle, s_angle = np.cos(rot), np.sin(rot)
            
            for line in m_lines:
                x = cx + c_angle * line[:, 0] - s_angle * line[:, 1]
                y = cy + s_angle * line[:, 0] + c_angle * line[:, 1]
                ax.plot(x, y, color=color, lw=lw, alpha=alpha, solid_capstyle="round")
                
            idx += 1
            
    fig.savefig(out_png, dpi=dpi, transparent=True)
    plt.close(fig)
    return out_png

# Monkey-patch the pattern generator
cover_hero.make_pattern = make_harmonograph_pattern

def main():
    spec = lulu_publish.BookSpec(
        pod_package_id="0850X1100.BW.STD.PB.060UW444.MXX",
        trim_w_in=8.5,
        trim_h_in=11.0,
        title="HARMONOGRAPH DREAMS",
        subtitle="A Mathematical Coloring Book",
        author="mathrelaxing",
        blurb=(
            "Fifty hand-crafted coloring pages generated by the mathematics of "
            "coupled pendulums. A harmonograph is a mechanical device from the 1800s "
            "that uses swinging weights to draw continuously looping, hypnotic curves. "
            "By carefully tuning the frequencies, damping factors, and phases, we've "
            "simulated these physical systems to create perfect geometric mandalas "
            "for you to color and relax."
        )
    )

    client = lulu_publish.make_client(sandbox=False)
    out_dir = os.path.join(_ROOT, "output")
    os.makedirs(out_dir, exist_ok=True)
    out_pdf = os.path.join(out_dir, "Harmonograph_Dreams_Cover.pdf")

    page_count = 104

    # NOTE: these are hand-colored sample pages, produced outside this repo
    # (e.g. colored in Procreate/Photoshop from the generated line art) —
    # supply your own, or drop this to gallery=[] for a cover with no gallery.
    harmo_dir = os.path.join(out_dir, "harmonographs_book")
    gallery = [
        os.path.join(harmo_dir, "page_01_Harmonographs_colored.png"),
        os.path.join(harmo_dir, "page_02_Harmonographs_colored.png"),
        os.path.join(harmo_dir, "page_10_Harmonographs_colored.png"),
    ]
    
    # Hero curves
    # We need to scale the hero curve so it fits nicely
    raw_hero = generate_harmonograph(777)
    # The default hero curve in cover_hero needs to fit roughly within 2-3 units.
    # The harmonograph output bounds can be ~5. Let's scale it down.
    scaled_hero = [line * 0.4 for line in raw_hero]
    cover_hero.DEFAULT_HERO = scaled_hero
    
    print("Building new cover PDF...")
    lulu_publish.build_cover_pdf(out_pdf, spec, page_count, client, gallery_pngs=gallery)
    print("Cover built successfully!")

if __name__ == "__main__":
    main()
