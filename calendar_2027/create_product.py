def up(path, name, tries=5):
    """Upload a q=88 copy (smaller payload) with retries; Printify sometimes times out on big files."""
    from PIL import Image
    small = os.path.join(OUT, "_up_" + os.path.basename(path))
    Image.open(path).save(small, quality=88)
    for k in range(tries):
        try:
            return pp.upload_image(small, file_name=name)
        except RuntimeError as e:
            print("   retry", k + 1, str(e)[:80]); time.sleep(5 * (k + 1))
    raise RuntimeError("upload failed: " + name)


def main():
    dry = "--dry" in sys.argv
    st = json.load(open(STATE)) if os.path.exists(STATE) else {}
    if "pid" not in st:
        ids = {}
        ids["front_cover"] = up(os.path.join(OUT, "00_cover.jpg"), "cal2027_cover.jpg")
        for i, (m, k) in enumerate(zip(MONTHS, KEYS), 1):
            ids[m] = up(os.path.join(OUT, f"{i:02d}_{k}.jpg"), f"cal2027_{i:02d}_{k}.jpg")
        ids["back_cover"] = up(os.path.join(OUT, "13_back.jpg"), "cal2027_back.jpg")
        payload = {
            "title": TITLE, "description": DESC, "blueprint_id": BP, "print_provider_id": PROV,
            "variants": [{"id": v, "price": p, "is_enabled": True} for v, p in PRICES.items()],
            "print_areas": [{"variant_ids": list(PRICES), "placeholders": [
                {"position": pos, "images": [{"id": iid, "x": 0.5, "y": 0.5, "scale": 1, "angle": 0}]} for pos, iid in ids.items()]}],
            "tags": TAGS,
        }
        prod = pp._req("POST", f"/shops/{pp.SHOP_ID}/products.json", payload)
        st = {"pid": prod["id"]}; json.dump(st, open(STATE, "w"), indent=1)
        for v in prod["variants"]:
            if v["is_enabled"]:
                print(f"  variant {v['title']}: cost ${v['cost'] / 100:.2f}  price ${v['price'] / 100:.2f}")
    if dry:
        return
    pp.publish_product(st["pid"]); print("publish requested")
    for _ in range(60):
        p = pp.get_product(st["pid"])
        if not p.get("is_locked") and (p.get("external") or {}).get("id"):
            break
        time.sleep(6)
    st["etsy"] = (p.get("external") or {}).get("id"); json.dump(st, open(STATE, "w"), indent=1)
    print("etsy listing", st["etsy"])


if __name__ == "__main__":
    main()
