def make(items, bp, prov, sizes, tags, desc_tpl, kind):
    out = []
    for fn, title, name, blurb in items:
        print(f"\n=== {kind}: {fn} ===")
        up = pp.upload_image(os.path.join(PR, fn), file_name=f"{kind}_{fn}")
        img_id = up if isinstance(up, str) else up["id"]
        prod = pp.create_poster(title[:140], desc_tpl.format(name=name, blurb=blurb),
                                img_id, sizes, tags=tags, blueprint_id=bp, provider_id=prov)
        pid = prod["id"]
        # margin sanity
        try:
            for v in prod.get("variants", [])[:1]:
                print(f"   sample variant cost={v.get('cost')} price={v.get('price')}")
        except Exception:
            pass
        pp.publish_product(pid)
        print(f"   published {pid} -> Etsy")
        out.append((name, pid))
    return out


def main():
    res = []
    res += [("TAPESTRY", n, p) for n, p in make(TAPESTRIES, TAP_BP, TAP_PROV, TAP_SIZES, TAP_TAGS, TAP_DESC, "tapestry")]
    res += [("BLANKET", n, p) for n, p in make(BLANKETS, BLK_BP, BLK_PROV, BLK_SIZES, BLK_TAGS, BLK_DESC, "blanket")]
    print("\n=== SUMMARY ===")
    for k, n, p in res:
        print(f"  {k:9} {n:32} printify {p}")


if __name__ == "__main__":
    main()
