"""
Create the fractal ceramic ornaments on Printify (blueprint 1599 "Ceramic Ornaments,
2-Side Print", provider 48 Colorway, Circle variant) with front + back artwork, then
publish each to the connected Etsy shop.

  python create_products.py            # create + publish all designs
  python create_products.py --dry koch # create one product only (no publish) to check cost
"""
import os, sys, json, time
HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(REPO, "printify")); sys.path.insert(0, HERE)
import printify_publish as pp
from designs import DESIGNS

BP, PROV, CIRCLE = 1599, 48, 111546
PRICE = 2199  # cents
OUT = os.path.join(HERE, "out")
STATE = os.path.join(HERE, "products.json")

TAGS = ["fractal ornament", "math ornament", "ceramic ornament", "math teacher gift", "science ornament",
        "geek christmas", "christmas ornament", "nerd ornament", "math lover gift", "stem gift",
        "mathematician gift", "physics gift", "unique ornament"]

TITLE = "{name} Ceramic Ornament, Math Christmas Ornament, Two-Sided Math Art, Gift for Math Teacher or Science Lover"
DESC = """{name} ceramic Christmas ornament, printed on both sides. Made to order.

The front shows {blurb}. The back names the shape and its math in gold lettering. Every design is computed from the mathematics itself, not drawn by hand and not AI.

- 100% ceramic, round, about 3 in / 7.5 cm across
- Vibrant print on BOTH sides
- Gold hanging cord included
- Printed and shipped to order by our print partner

A one-of-a-kind keepsake for math teachers, engineers, scientists, programmers and students, and a thoughtful little gift for anyone who loves numbers. Designed and generated by MathRelaxing."""


def load_state():
    return json.load(open(STATE)) if os.path.exists(STATE) else {}


def create(key, name, blurb):
    fid = pp.upload_image(os.path.join(OUT, f"{key}_front.png"), file_name=f"ornament_{key}_front.png")
    bid = pp.upload_image(os.path.join(OUT, f"{key}_back.png"), file_name=f"ornament_{key}_back.png")
    title = TITLE.format(name=name)
    if len(title) > 140:
        title = f"{name} Ceramic Ornament, Math Christmas Ornament, Gift for Math Teacher or Science Lover"
    payload = {
        "title": title[:140], "description": DESC.format(name=name, blurb=blurb),
        "blueprint_id": BP, "print_provider_id": PROV,
        "variants": [{"id": CIRCLE, "price": PRICE, "is_enabled": True}],
        "print_areas": [{"variant_ids": [CIRCLE], "placeholders": [
            {"position": "front", "images": [{"id": fid, "x": 0.5, "y": 0.5, "scale": 1, "angle": 0}]},
            {"position": "back", "images": [{"id": bid, "x": 0.5, "y": 0.5, "scale": 1, "angle": 0}]},
        ]}],
        "tags": TAGS,
    }
    prod = pp._req("POST", f"/shops/{pp.SHOP_ID}/products.json", payload)
    v = [x for x in prod["variants"] if x["id"] == CIRCLE][0]
    print(f"  {key}: product {prod['id']}  cost ${v['cost'] / 100:.2f}  price ${v['price'] / 100:.2f}")
    return prod["id"], v["cost"]


def wait_unlocked(pid, tries=40):
    for _ in range(tries):
        p = pp.get_product(pid)
        if not p.get("is_locked"):
            return p
        time.sleep(6)
    return pp.get_product(pid)


def main():
    args = sys.argv[1:]
    dry = "--dry" in args
    only = [a for a in args if not a.startswith("--")]
    state = load_state()
    for key, _, _, _, name, blurb in DESIGNS:
        if only and key not in only:
            continue
        if key in state:
            print(f"  {key}: already created ({state[key]['pid']})"); continue
        pid, cost = create(key, name, blurb)
        state[key] = {"pid": pid, "cost": cost}
        json.dump(state, open(STATE, "w"), indent=1)
        if not dry:
            pp.publish_product(pid); print(f"  {key}: publish requested")
    if not dry:
        for key, st in state.items():
            p = wait_unlocked(st["pid"])
            ext = (p.get("external") or {}).get("id")
            st["etsy"] = ext; print(f"  {key}: etsy listing {ext}")
        json.dump(state, open(STATE, "w"), indent=1)


if __name__ == "__main__":
    main()
