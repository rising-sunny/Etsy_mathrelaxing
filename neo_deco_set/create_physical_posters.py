"""Create the 3 Neo Deco POD poster products on Printify (blueprint 282 /
Printify Choice), push each to the connected Etsy shop, then set the resulting
Etsy listing to INACTIVE so the owner reviews before it goes live.

Only true 2:3 poster sizes are offered (12x18, 20x30, 24x36) so the 2:3 art is
never cropped. Masters are upscaled for a clean 300-ish DPI at large sizes.

  python create_physical_posters.py
"""
import os, sys, time
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
MAST = os.path.join(HERE, "masters")
sys.path.insert(0, os.path.join(REPO, "printify"))
sys.path.insert(0, REPO)
import printify_publish as pp
import etsy_manager
os.chdir(REPO)   # etsy_token.json is read relative to cwd

# true 2:3 variants on blueprint 282 / provider 99  (variant_id: retail cents)
SIZES = {43138: 2800, 43147: 4200, 43150: 5400}   # 12x18, 20x30, 24x36

TAGS = ["neo deco", "art deco print", "art deco wall art", "chrome wall art",
        "geometric wall art", "gold geometric art", "gatsby decor", "jewel tone art",
        "emerald wall art", "luxury wall art", "gallery wall art", "modern wall art",
        "statement wall art"]

DESIGNS = [
    ("01_sunburst", "Neo Deco Sunburst Poster | Art Deco Wall Art | Chrome Gold and Emerald Geometric Print",
     "rising-sun fan"),
    ("02_arches", "Neo Deco Arch Poster | Art Deco Geometric Wall Art | Gold and Platinum Portal Print",
     "nested arch portal"),
    ("03_rosette", "Neo Deco Rosette Poster | Art Deco Wall Art | Gold Chrome Emerald Medallion Print",
     "radial rose-window medallion"),
]

DESC_TMPL = """NEO DECO — {motif}, printed to order.

Old-world Art-Deco glamour reimagined for 2026: brushed gold and platinum foil geometry with an emerald jewel accent on a deep jewel-tone ground. The design is generated from exact geometry, so every line is crisp and the symmetry is perfect.

- Museum-quality matte poster, giclee-printed on heavyweight archival paper
- Sizes: 12x18, 20x30, 24x36 in (2:3)
- Printed and shipped to order by our print partner
- Frame not included

A statement piece for a living room, entryway or office; a glamorous gift for lovers of Gatsby / Art-Deco style. Designed and generated by MathRelaxing."""


def upscaled(path, target_w=6000):
    im = Image.open(path).convert("RGB")
    if im.width < target_w:
        r = target_w / im.width
        im = im.resize((target_w, int(im.height * r)), Image.LANCZOS)
    out = os.path.join(HERE, "_pf_" + os.path.basename(path).replace(".png", ".jpg"))
    im.save(out, quality=95)
    return out


def main():
    m = etsy_manager.EtsyManager()
    results = []
    for key, title, motif in DESIGNS:
        assert len(title) <= 140, f"title too long: {len(title)}"
        print("\n===", key, "===")
        big = upscaled(os.path.join(MAST, f"{key}.png"))
        up = pp.upload_image(big, file_name=f"neo_deco_{key}.jpg")
        img_id = up if isinstance(up, str) else up["id"]
        print("  uploaded image", img_id)
        prod = pp.create_poster(title, DESC_TMPL.format(motif=motif), img_id, SIZES, tags=TAGS)
        pid = prod["id"]; print("  product", pid)
        pp.publish_product(pid); print("  published -> Etsy")
        # resolve the Etsy listing id from the product's external mapping
        etsy_lid = None
        for _ in range(6):
            time.sleep(2)
            pr = pp.get_product(pid)
            ext = pr.get("external") or {}
            if ext.get("id"):
                etsy_lid = ext["id"]; break
        if etsy_lid:
            try:
                m.update_listing(etsy_lid, state="inactive")
                print("  Etsy listing", etsy_lid, "-> INACTIVE (owner reviews)")
            except Exception as e:
                print("  deactivate warn:", str(e)[:140])
        else:
            print("  (could not resolve Etsy listing id yet; check Printify)")
        results.append((key, pid, etsy_lid))
    print("\n=== SUMMARY ===")
    for k, pid, lid in results:
        print(f"  {k}: printify {pid} | etsy {lid}")


if __name__ == "__main__":
    main()
