"""Create the 9 Neo Deco *palette* POD posters (Ruby / Onyx / Amethyst x
Sunburst / Arch / Rosette) on Printify (blueprint 282 / Printify Choice) and
push each to the connected Etsy shop. True 2:3 sizes; masters upscaled for DPI.

  python create_palette_posters.py [palette ...]   # default: all three
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(REPO, "printify")); sys.path.insert(0, REPO)
import printify_publish as pp

SIZES = {43138: 2800, 43147: 4200, 43150: 5400}   # 12x18, 20x30, 24x36 (2:3)

PAL = {  # palette key -> (title colour phrase, ground word)
    "ruby":     ("Ruby and Gold", "deep ruby"),
    "onyx":     ("Onyx Black and Gold", "onyx black"),
    "amethyst": ("Amethyst and Gold", "amethyst"),
}
MOTIF = {  # slug -> (Name, motif phrase)
    "01_sunburst": ("Sunburst", "a rising-sun fan"),
    "02_arches":   ("Arch", "a nested arch portal"),
    "03_rosette":  ("Rosette", "a radial rose-window medallion"),
}

def tags(pal):
    return ["neo deco", "art deco print", "art deco wall art", "geometric wall art",
            "gold geometric art", "gatsby decor", "jewel tone art", f"{pal} wall art"[:20],
            "luxury wall art", "maximalist wall art", "gallery wall art", "modern wall art",
            "statement wall art"]

DESC = """Neo Deco {motif_name} — {motif}, in {ground}. Printed to order.

Old-world Art-Deco glamour reimagined for 2026: brushed gold and platinum foil
geometry with an emerald jewel accent on a {ground} ground. The design is
generated from exact geometry, so every line is crisp and the symmetry perfect.

- Museum-quality matte poster, giclee-printed on heavyweight archival paper
- Sizes: 12x18, 20x30, 24x36 in (2:3); frame not included
- Printed and shipped to order by our print partner

A statement piece for a living room, entryway or office; a glamorous gift for
lovers of Gatsby / Art-Deco style. Designed and generated by MathRelaxing."""


def upscaled(path, target_w=6000):
    im = Image.open(path).convert("RGB")
    if im.width < target_w:
        r = target_w / im.width
        im = im.resize((target_w, int(im.height * r)), Image.LANCZOS)
    out = os.path.join(HERE, "_pf_pal_" + os.path.basename(os.path.dirname(path)) + "_" +
                       os.path.basename(path).replace(".png", ".jpg"))
    im.save(out, quality=95)
    return out


def main(palettes):
    results = []
    for pal in palettes:
        colour, ground = PAL[pal]
        for slug, (mname, mphrase) in MOTIF.items():
            title = (f"Neo Deco {mname} Poster | {colour} Art Deco Wall Art | "
                     f"Metallic Geometric Print")[:140]
            assert title.count("&") <= 1
            src = os.path.join(HERE, "masters", pal, f"{slug}.png")
            print("\n===", pal, slug, "===")
            up = pp.upload_image(upscaled(src), file_name=f"neodeco_{pal}_{slug}.jpg")
            img_id = up if isinstance(up, str) else up["id"]
            prod = pp.create_poster(title, DESC.format(motif_name=mname, motif=mphrase, ground=ground),
                                    img_id, SIZES, tags=tags(pal))
            pid = prod["id"]; pp.publish_product(pid)
            print(f"  published {pid} -> Etsy")
            results.append((pal, slug, pid))
    print("\n=== SUMMARY ===")
    for pal, slug, pid in results:
        print(f"  {pal} {slug}: printify {pid}")


if __name__ == "__main__":
    pals = [a for a in sys.argv[1:] if a in PAL] or list(PAL.keys())
    main(pals)
