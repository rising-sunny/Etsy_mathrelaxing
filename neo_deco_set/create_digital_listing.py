"""Create the DRAFT digital Etsy listing for the Neo Deco set of 3 printables.
Stays in DRAFT (owner activates). Etsy auth = etsy_token.json at repo root.

  python create_digital_listing.py
"""
import os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
PREV = os.path.join(HERE, "previews")
ZIP = os.path.join(HERE, "Neo_Deco_Set.zip")
sys.path.insert(0, REPO)
os.chdir(REPO)
import etsy_manager

TAXONOMY_DIGITAL_PRINTS = 2078
PRICE = 14.00

TITLE = ("Neo Deco Set of 3 | Art Deco Wall Art Printable | Chrome Gold and Emerald "
         "Geometric Prints | Gatsby Gallery Wall Digital Download")

TAGS = [
    "neo deco", "art deco print", "art deco wall art", "chrome wall art",
    "geometric wall art", "gold geometric art", "gatsby decor", "jewel tone art",
    "gallery wall set", "emerald wall art", "luxury wall art", "printable wall art",
    "set of 3 prints",
]

DESC = """NEO DECO — a set of three metallic Art-Deco prints (instant download)

Old-world glamour, reimagined for 2026. Three statement prints — a rising Sunburst, a nested Arch Portal, and a radiant Rose Window — rendered in brushed gold and platinum foil with emerald jewel accents, each on a deep jewel-tone ground (emerald, midnight, sapphire). Every motif is generated from geometry, so the symmetry is exact and the detail is razor-sharp at any size.

— WHAT YOU GET —
- 3 high-resolution digital prints (JPEG, 300 DPI)
- Each design in THREE ratios: 2:3, 4:5 and ISO / A-size
- 2:3 prints at 4x6, 8x12, 12x18, 16x24, 20x30, 24x36 in
- 4:5 prints at 8x10, 16x20 in — A-size prints A5 through A1
- A tidy ZIP, organized and ready to print

— HOW IT WORKS —
- Instant download — no physical item is shipped
- Print at home, at a local shop, or upload to any online print service
- Colors may vary slightly by monitor and printer

— PERFECT FOR —
A living room, entryway or office gallery wall; a glamorous Gatsby / Art-Deco interior; a housewarming or wedding gift for someone with luxe taste.

For personal use only. Designed and generated by MathRelaxing."""

IMAGES = [
    "01_hero_gallery.jpg", "05_set_grid.jpg", "02_sunburst_mock.jpg",
    "03_arches_mock.jpg", "04_rosette_mock.jpg", "06_info.jpg",
]


def main():
    assert len(TITLE) <= 140, f"title too long: {len(TITLE)}"
    assert not any(c in TITLE for c in "^=+"), "forbidden char in title"
    for t in TAGS:
        assert len(t) <= 20, f"tag too long: {t}"
    print(f"title {len(TITLE)} chars | tags {len(TAGS)} | price ${PRICE}")

    m = etsy_manager.EtsyManager()
    lid = m.create_draft_listing(TITLE, DESC, PRICE, TAXONOMY_DIGITAL_PRINTS,
                                 is_digital=True, quantity=999, tags=TAGS)
    print("draft listing id:", lid)

    for rank, fn in enumerate(IMAGES, start=1):
        try:
            m.upload_listing_image(lid, os.path.join(PREV, fn), rank=rank)
            print("  image", fn)
        except Exception as e:
            print("  image err", fn, str(e)[:140])

    try:
        m.upload_listing_file(lid, ZIP)
        print("  digital file uploaded:", os.path.basename(ZIP))
    except Exception as e:
        print("  file err", str(e)[:160])

    print("\nDONE (DRAFT). https://www.etsy.com/listing/%s" % lid)
    return lid


if __name__ == "__main__":
    main()
