"""Create the 6 Resonance POD poster products on Printify (blueprint 282 /
Printify Choice) and push each to the connected Etsy shop. Listings publish
live/active (Printify has no draft step). True 2:3 sizes only, masters upscaled
for print DPI.

  python create_physical_posters.py
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
MAST = os.path.join(HERE, "masters")
sys.path.insert(0, os.path.join(REPO, "printify"))
sys.path.insert(0, REPO)
import printify_publish as pp
import generate_celestial as GC

SIZES = {43138: 2800, 43147: 4200, 43150: 5400}   # 12x18, 20x30, 24x36 (2:3)
TAGS = ["celestial wall art", "harmonograph art", "astronomy print", "math art print",
        "dark academia art", "gold celestial art", "science wall art", "geometric line art",
        "physics art print", "star map art", "office wall art", "modern wall art",
        "statement wall art"]

DESC_TMPL = """RESONANCE {ratio} — a celestial harmonograph, printed to order.

Two swinging pendulums trace the figure of two orbits locked in a {ratio}
resonance — one unbroken gold line on a deep night sky. Nothing hand-drawn:
the curve is computed from the mathematics of commensurate motion.

- Museum-quality matte poster, giclee-printed on heavyweight archival paper
- Sizes: 12x18, 20x30, 24x36 in (2:3)
- Printed and shipped to order by our print partner; frame not included

A statement piece for a dark-academia study, office or observatory-styled
gallery wall. Designed and generated by MathRelaxing."""


def upscaled(path, target_w=6000):
    im = Image.open(path).convert("RGB")
    if im.width < target_w:
        r = target_w / im.width
        im = im.resize((target_w, int(im.height * r)), Image.LANCZOS)
    out = os.path.join(HERE, "_pf_" + os.path.basename(path).replace(".png", ".jpg"))
    im.save(out, quality=95)
    return out


def main():
    results = []
    for key, ttl_full, sub, par in GC.RESONANCES[:6]:
        ratio = ttl_full.replace("RESONANCE ", "")
        title = (f"Resonance {ratio} Poster | Celestial Harmonograph Wall Art | "
                 f"Astronomy Math Print | Dark Academia Gold")[:140]
        print("\n===", key, ratio, "===")
        big = upscaled(os.path.join(MAST, f"{key}.png"))
        up = pp.upload_image(big, file_name=f"resonance_{key}.jpg")
        img_id = up if isinstance(up, str) else up["id"]
        prod = pp.create_poster(title, DESC_TMPL.format(ratio=ratio), img_id, SIZES, tags=TAGS)
        pid = prod["id"]
        pp.publish_product(pid)
        print(f"  published product {pid} -> Etsy")
        results.append((key, ratio, pid))
    print("\n=== SUMMARY (Printify product ids; Etsy listings publish async) ===")
    for k, r, pid in results:
        print(f"  {k} {r}: printify {pid}")


if __name__ == "__main__":
    main()
