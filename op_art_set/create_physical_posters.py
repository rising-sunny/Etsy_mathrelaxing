"""Create the 6 Kinetic op-art POD poster products on Printify (blueprint 282 /
Printify Choice) and push each to the connected Etsy shop (publishes live/active).

  python create_physical_posters.py
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
MAST = os.path.join(HERE, "masters")
sys.path.insert(0, os.path.join(REPO, "printify")); sys.path.insert(0, REPO)
import printify_publish as pp

SIZES = {43138: 2800, 43147: 4200, 43150: 5400}   # 12x18, 20x30, 24x36 (2:3)
TAGS = ["op art print", "optical illusion", "black and white art", "geometric wall art",
        "kinetic art", "mid century modern", "abstract wall art", "modern wall art",
        "retro wall art", "monochrome art", "op art poster", "statement wall art",
        "op art wall decor"]

DESIGNS = [
    ("01_vega", "Vega", "a grid pressed out into a sphere"),
    ("02_moire", "Moiré", "two fine gratings crossed into a shimmer"),
    ("03_vortex", "Vortex", "concentric rings dragged into a spiral"),
    ("04_fall", "Fall", "parallel curves compressed to a vibration"),
    ("05_flare", "Flare", "a radial burst flickering at the centre"),
    ("06_quanta", "Quanta", "nested square rings twisting inward"),
]

DESC_TMPL = """{name} — a kinetic op-art print, made to order.

In the lineage of Vasarely and Bridget Riley: {sub}. The illusion is computed
from a parametric distortion field — nothing hand-drawn — so it stays razor-sharp
at any size.

- Museum-quality matte poster, giclee-printed on heavyweight archival paper
- Sizes: 12x18, 20x30, 24x36 in (2:3)
- Printed and shipped to order by our print partner; frame not included

A bold statement for a modern living room, studio or office. Designed and
generated by MathRelaxing."""


def upscaled(path, target_w=6000):
    im = Image.open(path).convert("RGB")
    if im.width < target_w:
        r = target_w / im.width
        im = im.resize((target_w, int(im.height * r)), Image.LANCZOS)
    out = os.path.join(HERE, "_pf_" + os.path.basename(path).replace(".png", ".jpg"))
    im.save(out, quality=95)
    return out


def main():
    results = []
    for key, name, sub in DESIGNS:
        title = (f"{name} Op Art Poster | Black & White Optical Illusion Wall Art | "
                 f"Kinetic Geometric Print")[:140]
        assert title.count("&") <= 1
        print("\n===", key, name, "===")
        big = upscaled(os.path.join(MAST, f"{key}.png"))
        up = pp.upload_image(big, file_name=f"kinetic_{key}.jpg")
        img_id = up if isinstance(up, str) else up["id"]
        prod = pp.create_poster(title, DESC_TMPL.format(name=name, sub=sub), img_id, SIZES, tags=TAGS)
        pid = prod["id"]
        pp.publish_product(pid)
        print(f"  published product {pid} -> Etsy")
        results.append((key, name, pid))
    print("\n=== SUMMARY ===")
    for k, n, pid in results:
        print(f"  {k} {n}: printify {pid}")


if __name__ == "__main__":
    main()
