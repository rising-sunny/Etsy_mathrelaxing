"""Create Optical-Illusion (op-art) Jigsaw Puzzle POD products on Printify
(blueprint 616 / provider 1 SPOKE; 120 / 252 / 500 pieces, 5:4 landscape) and
push each to the connected Etsy shop.

  python create_puzzles.py
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
MAST = os.path.join(HERE, "masters")
sys.path.insert(0, os.path.join(REPO, "printify")); sys.path.insert(0, REPO)
import printify_publish as pp

BP, PROVIDER = 616, 1
SIZES = {72663: 2300, 72664: 2900, 72665: 3900}   # 120 / 252 / 500 pcs

TAGS = ["optical illusion puzzle", "op art puzzle", "black and white puzzle",
        "hard puzzle for adults", "mind bending puzzle", "geometric puzzle",
        "modern puzzle", "brain teaser gift", "difficult jigsaw", "trippy puzzle",
        "vasarely", "bridget riley art", "monochrome decor"]

# (crop file, Name, blurb)
PUZZLES = [
    ("vortex.jpg", "Vortex", "a hypnotic spiral that seems to turn while you look at it"),
    ("square.jpg", "Hypnos", "a square-spiral tunnel that drags your eye to its vanishing point"),
    ("wave.jpg", "Ripple", "Bridget Riley–style waves that ripple and breathe across the frame"),
    ("moire.jpg", "Harlequin", "interlocking diamonds that shimmer and shift as you move"),
]

DESC = """Optical Illusion Jigsaw Puzzle — {name}. Made to order.

{blurb}. Every stripe is computed from the mathematics — no clip-art, no AI — so
the high-contrast edges stay razor-sharp right down to the last piece. The
repeating black-and-white pattern makes this a genuinely challenging,
mesmerizing puzzle: a favorite of the "hardest puzzle" crowd.

- Sturdy chipboard jigsaw puzzle, crisp monochrome printing
- Sizes: 120, 252 and 500 pieces (choose above)
- Made and shipped to order by our print partner

A striking gift for design lovers, op-art fans and anyone who wants a puzzle
that fights back. Designed and generated by MathRelaxing."""


def upscaled(fn, target_w=6200):
    im = Image.open(os.path.join(MAST, fn)).convert("RGB")
    if im.width < target_w:
        r = target_w / im.width
        im = im.resize((target_w, int(im.height * r)), Image.LANCZOS)
    out = os.path.join(HERE, "_pf_" + fn)
    im.save(out, quality=95)
    return out


def main():
    results = []
    for fn, name, blurb in PUZZLES:
        title = (f"Optical Illusion Jigsaw Puzzle | Op Art {name} | Mind-Bending Hard Puzzle 252 500 Piece")[:140]
        print("\n===", fn, "===")
        up = pp.upload_image(upscaled(fn), file_name=f"opart_puzzle_{fn}")
        img_id = up if isinstance(up, str) else up["id"]
        prod = pp.create_poster(title, DESC.format(name=name, blurb=blurb), img_id, SIZES,
                                tags=TAGS, blueprint_id=BP, provider_id=PROVIDER)
        pid = prod["id"]; pp.publish_product(pid)
        print(f"  published {pid} -> Etsy")
        results.append((name, pid))
    print("\n=== SUMMARY ===")
    for name, pid in results:
        print(f"  {name}: printify {pid}")


if __name__ == "__main__":
    main()
