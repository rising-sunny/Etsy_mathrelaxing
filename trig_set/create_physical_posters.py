"""Create the 6 Trigonometry POD posters (portrait 2:3) on Printify
(blueprint 282 / provider 99) and push each to the connected Etsy shop.

  python create_physical_posters.py
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
MAST = os.path.join(HERE, "masters")
sys.path.insert(0, os.path.join(REPO, "printify")); sys.path.insert(0, REPO)
import printify_publish as pp

SIZES = {43138: 2600, 43147: 4000, 43150: 5200}   # 12x18, 20x30, 24x36 (portrait 2:3)
TAGS = ["trigonometry poster", "unit circle poster", "math classroom decor", "trig identities",
        "precalculus poster", "high school math", "math teacher gift", "algebra 2 poster",
        "sohcahtoa poster", "math wall art", "educational poster", "modern wall art",
        "classroom poster"]

DESIGNS = [
    ("unit_circle", "The Unit Circle", "angles, radians and coordinates on the unit circle"),
    ("sine_cosine", "Sine and Cosine", "the fundamental waves, amplitude and period"),
    ("right_triangle", "Right Triangle (SOHCAHTOA)", "the six ratios of a right triangle"),
    ("identities", "Trig Identities", "Pythagorean, reciprocal, sum and double-angle"),
    ("laws", "Law of Sines and Cosines", "solving any triangle"),
    ("tangent", "Tangent and Asymptotes", "period pi and the vertical asymptotes"),
]

DESC = """Trigonometry — {name}. Printed to order.

A clean classroom-ready trig plate ({sub}) in a warm graph-paper "scientific
plate" style. Every graph is computed from the mathematics.

- Museum-quality matte poster on heavyweight archival paper
- Sizes: 12x18, 20x30, 24x36 in (2:3); frame not included
- Printed and shipped to order by our print partner

Perfect for a math classroom, a tutor's wall or a student's study. Designed and
generated by MathRelaxing."""


def upscaled(path, target_w=6000):
    im = Image.open(path).convert("RGB")
    if im.width < target_w:
        r = target_w / im.width
        im = im.resize((target_w, int(im.height * r)), Image.LANCZOS)
    out = os.path.join(HERE, "_pf_" + os.path.basename(path).replace(".png", ".jpg"))
    im.save(out, quality=95)
    return out


def main():
    results = []
    for slug, name, sub in DESIGNS:
        title = (f"Trigonometry Poster | {name} | Math Classroom Wall Art")[:140]
        src = os.path.join(MAST, f"trig_{slug}.png")
        print("\n===", slug, "===")
        up = pp.upload_image(upscaled(src), file_name=f"trig_{slug}.jpg")
        img_id = up if isinstance(up, str) else up["id"]
        prod = pp.create_poster(title, DESC.format(name=name, sub=sub), img_id, SIZES, tags=TAGS)
        pid = prod["id"]; pp.publish_product(pid)
        print(f"  published {pid} -> Etsy")
        results.append((slug, pid))
    print("\n=== SUMMARY ===")
    for slug, pid in results:
        print(f"  {slug}: printify {pid}")


if __name__ == "__main__":
    main()
