"""Create the 4 Magnetic Pendulum square POD posters (3/4/5/6 magnets) on
Printify (blueprint 282 / provider 2, which offers square sizes) and push each
to the connected Etsy shop. Square art -> square poster (no crop).

  python create_physical_posters.py
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
MAST = os.path.join(HERE, "masters")
sys.path.insert(0, os.path.join(REPO, "printify")); sys.path.insert(0, REPO)
import printify_publish as pp

PROVIDER = 2                       # provider on blueprint 282 that has square sizes
SIZES = {101119: 2200, 101127: 2800, 101120: 3800}   # 10x10, 12x12, 16x16

TAGS = ["chaos theory art", "fractal wall art", "physics wall art", "magnetic pendulum",
        "science poster", "science wall art", "math wall art", "generative art",
        "geometric wall art", "basin attractor", "dynamical systems", "modern wall art",
        "statement wall art"]

N = {3: "Three", 4: "Four", 5: "Five", 6: "Six"}

DESC = """Chaos Theory — Magnetic Pendulum ({n} magnets). Printed to order.

A damped pendulum swings over {n} magnets; each point of this image is coloured
by the magnet the pendulum finally settles on, and shaded by how long it took.
Neighbouring starts can end on different magnets — the fingerprint of chaos and
sensitive dependence on initial conditions. Every mark is computed from the
equation of motion — nothing drawn, no AI.

- Square, museum-quality matte poster on heavyweight archival paper
- Sizes: 10x10, 12x12, 16x16 in; frame not included
- Printed and shipped to order by our print partner

A statement piece for a study, lab, office or classroom; a gift for physicists,
mathematicians and lovers of chaos theory. Designed and generated by MathRelaxing."""


def upscaled(path, target=6000):
    im = Image.open(path).convert("RGB")
    if im.width < target:
        im = im.resize((target, target), Image.LANCZOS)
    out = os.path.join(HERE, "_pf_" + os.path.basename(path).replace(".png", ".jpg"))
    im.save(out, quality=95)
    return out


def main():
    results = []
    for n in (3, 4, 5, 6):
        title = (f"Chaos Theory Poster | Magnetic Pendulum Fractal - {N[n]} Magnets | "
                 f"Physics Science Wall Art")[:140]
        src = os.path.join(MAST, f"pendulum_{n}.png")
        print("\n===", n, "magnets ===")
        up = pp.upload_image(upscaled(src), file_name=f"chaos_pendulum_{n}.jpg")
        img_id = up if isinstance(up, str) else up["id"]
        prod = pp.create_poster(title, DESC.format(n=N[n].lower()), img_id, SIZES,
                                tags=TAGS, blueprint_id=282, provider_id=PROVIDER)
        pid = prod["id"]; pp.publish_product(pid)
        print(f"  published {pid} -> Etsy")
        results.append((n, pid))
    print("\n=== SUMMARY ===")
    for n, pid in results:
        print(f"  {n} magnets: printify {pid}")


if __name__ == "__main__":
    main()
