"""Create the 6 Julia Set square POD posters on Printify (blueprint 282 /
provider 2, square sizes) and push each to the connected Etsy shop.

  python create_physical_posters.py
"""
import os, sys
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, ".."))
MAST = os.path.join(HERE, "masters")
sys.path.insert(0, os.path.join(REPO, "printify")); sys.path.insert(0, REPO)
import printify_publish as pp

PROVIDER = 2
SIZES = {101119: 2200, 101127: 2800, 101120: 3800}   # 10x10, 12x12, 16x16

TAGS = ["julia set art", "fractal wall art", "fractal art print", "math wall art",
        "chaos theory art", "science wall art", "generative art", "vibrant wall art",
        "mathematical art", "geometric wall art", "modern wall art", "abstract fractal",
        "statement wall art"]

DESIGNS = [
    ("dragon", "Dragon", "c = -0.8 + 0.156i"),
    ("rabbit", "Douady Rabbit", "c = -0.123 + 0.745i"),
    ("spiral", "Spiral", "c = -0.70176 - 0.3842i"),
    ("dense", "Filament", "c = 0.285 + 0.01i"),
    ("swirl", "Swirl", "c = -0.4 + 0.6i"),
    ("pinwheel", "Pinwheel", "c = 0.355 + 0.355i"),
]

DESC = """Julia Set — {name} ({c}). Printed to order.

A Julia set: iterate z -> z² + c across the complex plane and colour each point
by how it escapes to infinity. This one uses {c}, giving its own infinitely
detailed form in a vibrant electric palette. Every pixel is computed from the
equation — nothing drawn, no AI.

- Square, museum-quality matte poster on heavyweight archival paper
- Sizes: 10x10, 12x12, 16x16 in; frame not included
- Printed and shipped to order by our print partner

A bold statement for a study, lab, office or modern gallery wall; a gift for
mathematicians and lovers of fractals. Designed and generated by MathRelaxing."""


def upscaled(path, target=6000):
    im = Image.open(path).convert("RGB")
    if im.width < target:
        im = im.resize((target, target), Image.LANCZOS)
    out = os.path.join(HERE, "_pf_" + os.path.basename(path).replace(".png", ".jpg"))
    im.save(out, quality=95)
    return out


def main():
    results = []
    for slug, name, c in DESIGNS:
        title = (f"Julia Set Fractal Poster | {name} | Vibrant Math Chaos Wall Art")[:140]
        src = os.path.join(MAST, f"julia_{slug}.png")
        print("\n===", slug, "===")
        up = pp.upload_image(upscaled(src), file_name=f"julia_{slug}.jpg")
        img_id = up if isinstance(up, str) else up["id"]
        prod = pp.create_poster(title, DESC.format(name=name, c=c), img_id, SIZES,
                                tags=TAGS, blueprint_id=282, provider_id=PROVIDER)
        pid = prod["id"]; pp.publish_product(pid)
        print(f"  published {pid} -> Etsy")
        results.append((slug, pid))
    print("\n=== SUMMARY ===")
    for slug, pid in results:
        print(f"  {slug}: printify {pid}")


if __name__ == "__main__":
    main()
