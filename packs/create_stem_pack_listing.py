"""Create DRAFT Etsy digital listing for STEM Wall Art Pack of 10, then activate.

Run from repo root:
  python packs/build_stem_pack.py
  python packs/create_stem_pack_listing.py
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
os.chdir(ROOT)

import etsy_manager
from etsy_manager import EtsyManager

PACK_DIR = os.path.join(ROOT, "packs", "stem_wall_art_10")
# Etsy digital file limit ~20MB each — split pack into 2 zips
ZIPS = [
    os.path.join(PACK_DIR, "MathRelaxing_STEM_Pack_Part1_of_2.zip"),
    os.path.join(PACK_DIR, "MathRelaxing_STEM_Pack_Part2_of_2.zip"),
]
IMAGES = [
    os.path.join(PACK_DIR, "preview_1_hero.jpg"),
    os.path.join(PACK_DIR, "preview_2_included.jpg"),
    os.path.join(PACK_DIR, "preview_3_value.jpg"),
]

# Digital Prints taxonomy
TAXONOMY = 2078
PRICE = 16.99

TITLE = (
    "STEM Wall Art Pack of 10 | Math Physics Digital Prints Bundle | "
    "Famous Equations Unit Circle Classroom Office Decor"
)

TAGS = [
    "math wall art",
    "physics poster",
    "stem wall art",
    "math poster pack",
    "science wall art",
    "classroom decor",
    "digital download",
    "math teacher gift",
    "equation poster",
    "unit circle",
    "printable wall art",
    "office wall art",
    "physics art print",
]

DESC = """STEM WALL ART PACK — 10 DESIGNS
A curated bundle of MathRelaxing bestsellers: equations, geometry, and physics prints for classroom, office, dorm or studio.

— WHAT'S INCLUDED (instant download) —
1. Famous Equations — set of 6 scientific plates
2. Unit Circle — trigonometry reference poster
3. Ulam Spiral — prime numbers art print
4. Euler's Identity — complex plane art print
5. Black Hole Anatomy — Schwarzschild physics print
6. Schrödinger Equation — quantum mechanics print
7. Platonic Solids — sacred geometry poster
8. Special Functions — set of 6 scientific plates
9. Harmonic Series / Vibrating String
10. Fourier Series

Two ZIP downloads (Part 1 + Part 2) with 10 folders of print-ready files (high-resolution JPG/PDF as provided).

— VALUE —
Bought separately these designs are ~$30+. Pack price: $16.99.

— PERFECT FOR —
Math teachers, physics students, STEM gifts, gallery walls, classroom decor, home office.

Designed and generated by MathRelaxing. Personal use only.
"""


def main():
    for p in [*ZIPS, *IMAGES]:
        if not os.path.isfile(p):
            raise SystemExit(f"Missing {p} — run packs/build_stem_pack.py first")
        mb = os.path.getsize(p) / (1024 * 1024)
        if p.endswith(".zip") and mb > 19.5:
            raise SystemExit(f"Zip too large for Etsy ({mb:.1f} MB): {p}")

    m = EtsyManager()
    lid = m.create_full_product(
        TITLE,
        DESC,
        PRICE,
        TAXONOMY,
        image_paths=IMAGES,
        digital_file_paths=ZIPS,
        tags=TAGS,
    )
    print("Draft listing_id:", lid)

    # Activate
    shop = m.get_shop_id()
    try:
        m.make_request(
            "PATCH",
            f"/shops/{shop}/listings/{lid}",
            payload={"state": "active", "who_made": "i_did", "when_made": "2020_2026", "is_supply": False},
            json_body=True,
        )
        print("Activated.")
    except Exception as e:
        print("Activate warn:", e)
        try:
            m.update_listing(lid, state="active")
            print("Activated via update_listing.")
        except Exception as e2:
            print("Still draft — activate manually:", e2)

    full = m.make_request("GET", f"/listings/{lid}")
    print("state:", full.get("state"))
    print("url:", full.get("url") or f"https://www.etsy.com/listing/{lid}")
    print("price:", full.get("price"))
    return lid


if __name__ == "__main__":
    main()
