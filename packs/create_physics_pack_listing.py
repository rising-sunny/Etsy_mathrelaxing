"""Create + activate Etsy digital listing for Physics Wall Art Pack of 10.

Run from repo root:
  python packs/build_physics_pack.py
  python packs/create_physics_pack_listing.py
"""
from __future__ import annotations

import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
os.chdir(ROOT)

from etsy_manager import EtsyManager

PACK_DIR = os.path.join(ROOT, "packs", "physics_wall_art_10")
ZIPS = [
    os.path.join(PACK_DIR, "MathRelaxing_Physics_Pack_Part1_of_2.zip"),
    os.path.join(PACK_DIR, "MathRelaxing_Physics_Pack_Part2_of_2.zip"),
]
IMAGES = [
    os.path.join(PACK_DIR, "preview_1_hero.jpg"),
    os.path.join(PACK_DIR, "preview_2_included.jpg"),
    os.path.join(PACK_DIR, "preview_3_value.jpg"),
]

TAXONOMY = 2078  # Digital Prints
PRICE = 16.99

TITLE = (
    "Physics Wall Art Pack of 10 | Science Digital Prints Bundle | "
    "Maxwell Schrodinger Black Hole Classroom Office Decor"
)

TAGS = [
    "physics poster",
    "physics wall art",
    "science wall art",
    "stem wall art",
    "physics art print",
    "classroom decor",
    "digital download",
    "physics teacher gift",
    "equation poster",
    "quantum physics",
    "printable wall art",
    "science classroom",
    "lab decor",
]

DESC = """PHYSICS WALL ART PACK — 10 DESIGNS
A curated digital bundle of MathRelaxing physics prints for classroom, lab, office or studio walls.

— WHAT'S INCLUDED (instant download) —
1. Maxwell Electromagnetism
2. Schrödinger Equation — quantum mechanics
3. Black Hole Anatomy — Schwarzschild physics
4. Wave Equation
5. Dirac Equation
6. Navier–Stokes equations
7. Fourier Series
8. Harmonic Series / Vibrating String
9. Special Functions — set of 6 scientific plates
10. Hermite / Quantum Harmonic Oscillator

Two ZIP downloads (Part 1 + Part 2) with 10 folders of print-ready files (high-resolution JPG/PDF as provided).

— VALUE —
Bought separately these designs are ~$30+. Pack price: $16.99.

— PERFECT FOR —
Physics teachers, engineering students, STEM gifts, science classroom decor, home office.

Designed and generated by MathRelaxing. Personal use only.
"""


def main():
    for p in [*ZIPS, *IMAGES]:
        if not os.path.isfile(p):
            raise SystemExit(f"Missing {p} — run packs/build_physics_pack.py first")
        mb = os.path.getsize(p) / (1024 * 1024)
        if p.endswith(".zip") and mb > 19.5:
            raise SystemExit(f"Zip too large for Etsy ({mb:.1f} MB): {p}")

    m = EtsyManager()
    lid = m.create_full_product(
        TITLE,
        DESC,
        PRICE,
        TAXONOMY,
        image_paths=IMAGES,
        digital_file_paths=ZIPS,
        tags=TAGS,
    )
    print("Draft listing_id:", lid)

    shop = m.get_shop_id()
    try:
        m.make_request(
            "PATCH",
            f"/shops/{shop}/listings/{lid}",
            payload={
                "state": "active",
                "who_made": "i_did",
                "when_made": "2020_2026",
                "is_supply": False,
            },
            json_body=True,
        )
        print("Activated.")
    except Exception as e:
        print("Activate warn:", e)
        try:
            m.update_listing(lid, state="active")
            print("Activated via update_listing.")
        except Exception as e2:
            print("Still draft — activate manually:", e2)

    full = m.make_request("GET", f"/listings/{lid}")
    print("state:", full.get("state"))
    print("url:", full.get("url") or f"https://www.etsy.com/listing/{lid}")
    print("price:", full.get("price"))
    return lid


if __name__ == "__main__":
    main()
